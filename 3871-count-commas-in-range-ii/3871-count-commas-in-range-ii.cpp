class Solution {
public:
    long long countCommas(long long n) {
        if(n<1000)
            return(0);
        else if(1000<=n && n<1000000)
            return(n-999);
        else if(1000000<=n && n<1000000000)
            return((n-999999)*2 + 999000);
        else if(1000000000<=n && n<1000000000000)
            return((n-999999999)*3 + (999000000*2) +999000);
        else if(1000000000000<=n && n<1000000000000000)
            return((n-999999999999)*4 + (999000000000*3) + (999000000*2) + 999000);
        else
            return((n-999999999999999)*5 + (999000000000000*4) + (999000000000*3) + (999000000*2) + 999000);
    }
};